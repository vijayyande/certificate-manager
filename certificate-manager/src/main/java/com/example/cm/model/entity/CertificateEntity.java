package com.example.cm.model.entity;

import com.example.cm.model.enums.CertificateStatus;
import com.example.cm.model.enums.KeyStorage;
import com.fasterxml.jackson.annotation.JsonIgnore;
import com.fasterxml.jackson.databind.annotation.JsonSerialize;
import com.fasterxml.jackson.databind.ser.std.ToStringSerializer;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.math.BigInteger;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

@Entity
@Table(name = "certificates")
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class CertificateEntity {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    private String commonName;

    private String subjectDn;

    @JsonSerialize(using = ToStringSerializer.class)
    @Column(length = 80)
    private String serialNumber;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private CertificateStatus status = CertificateStatus.PENDING;

    @Column(columnDefinition = "TEXT")
    private String csrPem;

    @Column(columnDefinition = "TEXT")
    private String certificatePem;

    @Column(columnDefinition = "TEXT")
    private String publicKeyPem;

    /** Private key, only present for requests generated by the platform (manual entry). Never serialized. */
    @JsonIgnore
    @Column(columnDefinition = "TEXT")
    private String privateKeyPem;

    /** Where the platform-generated private key lives: DATABASE (PEM) or PKCS11 (token-resident). */
    @Enumerated(EnumType.STRING)
    @Builder.Default
    @Column(length = 20)
    private KeyStorage keyStorage = KeyStorage.DATABASE;

    /** Token alias when the private key resides on the PKCS#11 device. */
    private String pkcs11Alias;

    private String keyAlgorithm;

    private Integer keySize;

    /** Signature algorithm of the issued certificate (the issuer CA's signature algorithm). */
    private String signatureAlgorithm;

    private Integer validityDays;

    /** Fine-grained validity in minutes (null when validityDays was used). */
    private Integer validityMinutes;

    private Long issuerCaId;

    private LocalDateTime validFrom;

    private LocalDateTime validTo;

    private LocalDateTime revokedAt;

    private LocalDateTime suspendedAt;

    private String revocationReason;

    private String requestedBy;

    private String approverName;

    private LocalDateTime createdAt;

    private LocalDateTime issuedAt;

    /** Certificate profile applied to this request, if any. */
    private String profileName;

    /** Profile-driven basicConstraints CA:TRUE (administrator only). */
    private boolean caProfile;

    @ElementCollection(fetch = FetchType.EAGER)
    @CollectionTable(name = "certificate_key_usages", joinColumns = @JoinColumn(name = "certificate_id"))
    @Column(name = "key_usage")
    private List<String> keyUsage = new ArrayList<>();

    @ElementCollection(fetch = FetchType.EAGER)
    @CollectionTable(name = "certificate_extended_key_usages", joinColumns = @JoinColumn(name = "certificate_id"))
    @Column(name = "extended_key_usage")
    private List<String> extendedKeyUsage = new ArrayList<>();

    @Convert(converter = CustomExtensionConverter.class)
    @Column(columnDefinition = "TEXT")
    private List<CustomExtension> additionalExtensions = new ArrayList<>();

    /** True when the platform generated a key pair for this request (downloadable via GET /api/certificates/{id}/key). */
    public boolean isPrivateKeyAvailable() {
        return privateKeyPem != null;
    }
}
